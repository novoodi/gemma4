D = []

def add(id_, chat_date, case, participants, msgs, gold, extra_names=(), phones=(), emails=()):
    pids = list(participants)
    in_text = {}
    text_all = "\n".join(t for _, t in msgs)
    for nm in participants.values():
        g = nm[1:]
        c = text_all.count(g)
        if c:
            in_text[g] = c
    for nm in extra_names:
        c = text_all.count(nm)
        if c:
            in_text[nm] = c
    D.append({
        "id": f"syn-{id_}", "source": "synthetic", "case": case, "topic": "모임",
        "chat_date": chat_date, "n_participants": len(pids), "n_messages": len(msgs),
        "participants": [{"pid": p, "name": n} for p, n in participants.items()],
        "messages": [{"pid": p, "sender": participants[p], "text": t, "date": chat_date, "time": None} for p, t in msgs],
        "reference_summary": gold.pop("summary"),
        "gold": {**gold, "pii_injected": {"participant_names": list(participants.values()), "in_text_names": in_text,
                                          "third_party_names": list(extra_names), "phones": list(phones), "emails": list(emails)},
                 "pii_decoys": gold.get("pii_decoys", []), "augmented": []},
        "human_review": {"reviewer": "synthetic", "verified": True, "notes": "작성 시 정답 동봉"},
    })


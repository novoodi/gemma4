KINDS = ["lexical", "lexical", "paraphrase", "paraphrase", "intent"]


def main():
    out = Path(".eval-local/evalset"); out.mkdir(parents=True, exist_ok=True)
    feedbacks = [{"id": fid, "text": text} for fid, text, _ in CORPUS]
    queries = []
    for fid, _, qs in CORPUS:
        assert len(qs) == 5, fid
        for k, q in enumerate(qs):
            queries.append({"id": f"{fid}-q{k + 1}", "text": q, "kind": KINDS[k], "gold": fid})
    doc = {"version": 1, "feedbacks": feedbacks, "queries": queries}
    (out / "feedback_corpus.json").write_text(json.dumps(doc, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"feedbacks={len(feedbacks)} queries={len(queries)} → {out / 'feedback_corpus.json'}")


if __name__ == "__main__":
    main()
